"""Regressions for effective scope inputs and evidence-backed exclusions."""
from pathlib import Path
import re
import unittest

from sonar_scan_policy import matches, properties

ROOT = Path(__file__).resolve().parent.parent


def excluded(path, properties):
    return any(matches(path, pattern)
               for pattern in properties['sonar.exclusions'].split(','))


class SonarClassificationTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.properties = properties(ROOT)

    def test_handwritten_mock_helpers_remain_available_for_analysis(self):
        for path in sorted((ROOT / 'pkg/models/mocks').glob('*.go')):
            if not re.search(r'^// Code generated .*DO NOT EDIT\.',
                             path.read_text(), re.M):
                with self.subTest(path=path.name):
                    self.assertFalse(excluded(path.relative_to(ROOT).as_posix(),
                                          self.properties))

    def test_generated_mock_exclusions_have_generator_evidence(self):
        generated = list((ROOT / 'pkg/models/mocks').glob('*ReaderWriter.go'))
        self.assertTrue(generated)
        for path in generated:
            with self.subTest(path=path.name):
                self.assertRegex(path.read_text().splitlines()[0],
                                 r'^// Code generated by mockery .*DO NOT EDIT\.')
                self.assertTrue(excluded(path.relative_to(ROOT).as_posix(),
                                         self.properties))

    def test_ignored_legacy_scope_properties_are_absent(self):
        for key in ('sonar.sources', 'sonar.tests', 'sonar.test.inclusions',
                    'sonar.test.exclusions'):
            self.assertNotIn(key, self.properties)

    def test_tests_support_and_handwritten_sources_remain_available(self):
        for path in ('pkg/cache/lru_test.go',
                     'ui/v2.5/src/hooks/useLocalStorage.test.tsx',
                     'ui/v2.5/src/test/setup.ts',
                     'scripts/test_sonar_scan_policy.py',
                     'scripts/test_db_generator/scene.txt',
                     'pkg/cache/testdata/fixture.json',
                     'pkg/models/paths/paths_generated.go'):
            with self.subTest(path=path):
                self.assertFalse(excluded(path, self.properties))


if __name__ == '__main__':
    unittest.main()
