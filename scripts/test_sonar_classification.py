"""Regressions for effective scope inputs and evidence-backed exclusions."""
from pathlib import Path
import re
import unittest

from sonar_scan_policy import matches, properties

ROOT = Path(__file__).resolve().parent.parent


def excluded(path, properties):
    return any(matches(path, pattern)
               for pattern in properties['sonar.exclusions'].split(','))


def coverage_excluded(path, properties):
    return any(matches(path, pattern)
               for pattern in properties['sonar.coverage.exclusions'].split(','))


class SonarClassificationTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.properties = properties(ROOT)

    def test_handwritten_mock_helpers_remain_available_for_analysis(self):
        for path in sorted((ROOT / 'pkg/models/mocks').glob('*.go')):
            if not re.search(r'^// Code generated .*DO NOT EDIT\.',
                             path.read_text(), re.M):
                with self.subTest(path=path.name):
                    self.assertFalse(excluded(path.relative_to(ROOT).as_posix(),
                                          self.properties))

    def test_generated_mock_exclusions_have_generator_evidence(self):
        generated = list((ROOT / 'pkg/models/mocks').glob('*ReaderWriter.go'))
        self.assertTrue(generated)
        for path in generated:
            with self.subTest(path=path.name):
                self.assertRegex(path.read_text().splitlines()[0],
                                 r'^// Code generated by mockery .*DO NOT EDIT\.')
                self.assertTrue(excluded(path.relative_to(ROOT).as_posix(),
                                         self.properties))

    def test_ignored_legacy_scope_properties_are_absent(self):
        for key in ('sonar.sources', 'sonar.tests', 'sonar.test.inclusions',
                    'sonar.test.exclusions'):
            self.assertNotIn(key, self.properties)

    def test_tests_support_and_handwritten_sources_remain_available(self):
        for path in ('pkg/cache/lru_test.go',
                     'ui/v2.5/src/hooks/useLocalStorage.test.tsx',
                     'ui/v2.5/src/test/setup.ts',
                     'scripts/test_sonar_scan_policy.py',
                     'scripts/test_db_generator/scene.txt',
                     'pkg/cache/testdata/fixture.json',
                     'pkg/models/paths/paths_generated.go'):
            with self.subTest(path=path):
                self.assertFalse(excluded(path, self.properties))

    def test_every_test_file_is_excluded_from_coverage_metrics(self):
        # Unexcluded test lines count as uncovered production code server-side.
        candidates = []
        for root in ('cmd', 'internal', 'pkg', 'scripts',
                     'ui/v2.5/scripts', 'ui/v2.5/src'):
            candidates.extend(sorted((ROOT / root).rglob('*')))
        tests = []
        for path in candidates:
            if not path.is_file():
                continue
            rel = path.relative_to(ROOT).as_posix()
            if (path.name.endswith('_test.go')
                    or path.name.startswith('test_') and path.suffix == '.py'
                    or '.test.' in path.name or '.spec.' in path.name
                    or rel.startswith('ui/v2.5/src/test/')):
                tests.append(rel)
        self.assertTrue(tests)
        for path in tests:
            with self.subTest(path=path):
                self.assertTrue(coverage_excluded(path, self.properties))

    def test_production_sources_keep_coverage_metrics(self):
        for path in ('pkg/cache/lru.go',
                     'ui/v2.5/src/App.tsx',
                     'scripts/sonar_scan_policy.py'):
            with self.subTest(path=path):
                self.assertFalse(coverage_excluded(path, self.properties))

    def test_sqlite_migration_sql_is_excluded_but_go_migrations_remain(self):
        # Sonar analyzes every .sql file as Oracle PL/SQL; these are SQLite.
        migrations = ROOT / 'pkg/sqlite/migrations'
        sql = sorted(migrations.glob('*.sql'))
        go = sorted(migrations.glob('*.go'))
        self.assertTrue(sql and go)
        for path in sql + go:
            with self.subTest(path=path.name):
                self.assertEqual(excluded(path.relative_to(ROOT).as_posix(), self.properties),
                                 path.suffix == '.sql')


if __name__ == '__main__':
    unittest.main()
