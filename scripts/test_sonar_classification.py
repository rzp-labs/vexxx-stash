"""Regressions for source/test partitioning and evidence-backed mock exclusions."""
from pathlib import Path
import re
import subprocess
import unittest

ROOT = Path(__file__).resolve().parent.parent


def load_properties(path):
    return dict(line.split('=', 1) for line in path.read_text().splitlines()
                if line and not line.startswith('#'))


def matches(path, pattern):
    # Sonar path patterns: ** spans directories, * and ? stay within one.
    regex = ''
    i = 0
    while i < len(pattern):
        if pattern[i:i + 3] == '**/':
            regex += '(?:.*/)?'
            i += 3
        elif pattern[i:i + 2] == '**':
            regex += '.*'
            i += 2
        elif pattern[i] == '*':
            regex += '[^/]*'
            i += 1
        elif pattern[i] == '?':
            regex += '[^/]'
            i += 1
        else:
            regex += re.escape(pattern[i])
            i += 1
    return bool(re.fullmatch(regex, path))


def classification(path, properties):
    def patterns(key):
        return properties.get(key, '').split(',')

    def within(key):
        return any(path == p or path.startswith(p.rstrip('/') + '/')
                   for p in patterns(key))

    def filtered(key):
        return any(matches(path, p) for p in patterns(key))

    # Sonar automatically adds test inclusions to source exclusions.
    is_test = (within('sonar.tests') and filtered('sonar.test.inclusions')
               and not filtered('sonar.test.exclusions'))
    is_source = (within('sonar.sources') and not filtered('sonar.exclusions')
                 and not filtered('sonar.test.inclusions'))
    return is_source, is_test


class SonarClassificationTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.properties = load_properties(ROOT / 'sonar-project.properties')

    def test_handwritten_mock_helpers_are_analyzed_as_tests(self):
        for path in sorted((ROOT / 'pkg/models/mocks').glob('*.go')):
            if not re.search(r'^// Code generated .*DO NOT EDIT\.',
                             path.read_text(), re.M):
                with self.subTest(path=path.name):
                    self.assertEqual(classification(path.relative_to(ROOT).as_posix(),
                                                    self.properties), (False, True))

    def test_generated_mock_exclusions_have_generator_evidence(self):
        generated = list((ROOT / 'pkg/models/mocks').glob('*ReaderWriter.go'))
        self.assertTrue(generated)
        for path in generated:
            with self.subTest(path=path.name):
                self.assertRegex(path.read_text().splitlines()[0],
                                 r'^// Code generated by mockery .*DO NOT EDIT\.')
                self.assertEqual(classification(path.relative_to(ROOT).as_posix(),
                                                self.properties), (False, False))

    def test_tracked_tests_and_support_have_disjoint_scope(self):
        tracked = subprocess.check_output(['git', 'ls-files', '-z'], cwd=ROOT,
                                          text=True).split('\0')
        for path in filter(None, tracked):
            is_source, is_test = classification(path, self.properties)
            with self.subTest(path=path):
                self.assertFalse(is_source and is_test)
                if (path.endswith(('_test.go', '.test.ts', '.test.tsx',
                                   '.spec.ts', '.spec.tsx', '.test.mjs'))
                        or re.search(r'/test_[^/]*\.py$', path)
                        or path.startswith('ui/v2.5/src/test/')):
                    self.assertEqual((is_source, is_test), (False, True))
        self.assertEqual(classification('pkg/models/paths/paths_generated.go',
                                        self.properties), (True, False))


if __name__ == '__main__':
    unittest.main()
